/* Topic: Input/Output - escape sequences */
#include <stdio.h>

int main()
{
    printf("New line  : Hello\\nWorld ->\nHello\nWorld\n");
    printf("Tab       : A\tB\tC\n");
    printf("Backslash : C:\\Users\\BCA\n");
    printf("Quotes    : \"C Language\" and \'c\'\n");
    printf("Percent   : 100%%\n");
    return 0;
}
